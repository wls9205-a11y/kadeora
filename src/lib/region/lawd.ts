/** 라벨 목록. 호출 예산을 «라벨 수» 로 세면 창원 5개 구가 1건이 되어 틀린다. */
export const LAWD_LABELS: readonly string[] = Object.keys(SIGUNGU_LAWD_CODES);

/**
 * `[라벨, 코드]` 로 편 목록. 외부 API 호출은 «코드» 단위이므로 예산 계산은 이것으로 한다.
 * (`LAWD_LABELS.length` 이 아니라 `LAWD_ENTRIES.length` 가 호출 수다.)
 */
export const LAWD_ENTRIES: ReadonlyArray<readonly [string, string]> = Object.entries(
  SIGUNGU_LAWD_CODES,
).flatMap(([label, codes]) => codes.map((code) => [label, code] as const));

/** 코드 → 라벨 역인덱스. 응답의 `sggCd` 가 요청한 지역인지 대조할 때 쓴다. */
const LABEL_BY_CODE: ReadonlyMap<string, string> = new Map(
  LAWD_ENTRIES.map(([label, code]) => [code, label]),
);

/** 시도 → 코드 앞 2자리. 표에서 «유도» 한다 — 두 번째 진실을 만들지 않기 위해서다. */
export const SIDO_PREFIX: ReadonlyMap<string, string> = (() => {
  const m = new Map<string, string>();
  for (const [label, code] of LAWD_ENTRIES) m.set(parseRegionSigungu(label).region, code.slice(0, 2));
  return m;
})();

/** 라벨의 코드 목록. 없는 라벨은 빈 배열 — 호출부에서 「돌았는데 0건」과 구분되도록 한다. */
export function lawdCodesOf(label: string): readonly string[] {
  return SIGUNGU_LAWD_CODES[label] ?? [];
}

/** 코드가 속한 라벨. 모르는 코드면 null. */
export function labelOfLawdCode(code: string): string | null {
  return LABEL_BY_CODE.get(code) ?? null;
}

