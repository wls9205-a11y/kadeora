// 아파트 현장명 → URL slug.
//
// ⚠️ 이 파일이 **유일한 원본**이다. 다른 곳에 slug 생성을 다시 만들지 말 것.
//    중복 256쌍(V15 A-1)이 규칙이 두 벌이던 결과다.
//
// ── 규칙 ──
//   1. 앞뒤 공백 제거
//   2. 공백(연속 포함) → 하이픈 하나
//   3. 한글·영숫자·밑줄·하이픈 외 전부 제거
//   4. 영문은 **소문자로 보존한다** — 지우지 않는다.
//      영문 토막을 지우던 규칙이 `DMC SK VIEW 아이파크포레` → `---아이파크포레` 를 만들었다.
//      그 규칙은 이미 코드에 없다 (실측: 깨진 slug 최신 생성 2026-03-24, 최신 행 2026-08-23).
//
// ⚠️ **기존 slug 를 바꾸지 말 것.** 색인이 걸려 있고 `apt_site_merges` 301 맵도
//    기존 값 기준이다. 활성 160행이 아직 깨진 형태(`^-` · `--` · `-$`)를 쓴다.

/**
 * 느슨한 규칙 — **기존 데이터와 호환되는 형태**.
 *
 * 조회·링크 폴백에서 쓴다.
 *
 * V19 A: DB 담당이 깨진 slug 를 정리해 **활성 깨진 slug 가 0** 이 됐고,
 * `sync-apt-sites` 는 strict 로 넘어갔다. 이 함수는 aptHref 폴백 등
 * **기존 값과 맞춰야 하는 자리**에만 남는다.
 *
 * ⚠️ 이 규칙은 하이픈 주변 공백에서 연속 하이픈을 만든다:
 *      `e편한세상 - 가평` → `e편한세상---가평`
 *    알고도 그대로 두는 이유는 위와 같다. 새 레코드에는 아래 strict 를 쓴다.
 */
export function generateAptSlug(name: string): string {
  if (!name || !name.trim()) return '';
  return name
    .trim()
    .replace(/\s+/g, '-')
    .replace(/[^\w가-힣\-]/g, '')
    .toLowerCase();
}

/**
 * 엄격한 규칙 — **새로 만드는 레코드에만** 쓴다.
 *
 * 느슨한 규칙에 두 가지를 더한다.
 *   - 연속 하이픈을 하나로
 *   - 앞뒤 하이픈 제거
 *
 * ⚠️ 기존 행을 조회하는 경로에 쓰지 말 것. 느슨한 값으로 저장된 행을 못 찾는다.
 *    쓰는 곳은 "이 이름으로 저장된 행이 없음을 이미 확인한" 생성 경로뿐이다
 *    (어드민 한 줄 입력 등).
 *
 * ── ⚠️ 구분기호(`·` `(` `)` `,`)는 **지운다. 하이픈으로 바꾸지 않는다** ──
 *   광안동 부흥·부광 소규모재건축  → 광안동-부흥부광-소규모재건축
 *   남천2-3(삼익비치) 재건축       → 남천2-3삼익비치-재건축
 *   구서동(금화,산호,삼산) 소규모재건축 → 구서동금화산호삼산-소규모재건축
 *
 *   왜 지우는 쪽인가: 기존 데이터가 그렇다. 특수문자가 든 활성 현장 670건 실측 —
 *   **지우는 형태 412건 : 하이픈으로 바꾸는 형태 30건.** 규칙을 뒤집으면
 *   412건이 재동기화 때 전부 새 slug 를 얻어 쌍둥이가 된다.
 *
 *   ⚠️ 이 규칙을 "읽기 좋게" 바꾸고 싶어질 것이다. 바꾸지 말 것.
 *      중복 14쌍(2026-08-25 정리)이 규칙이 두 갈래였던 결과다.
 *      가독성이 필요하면 slug 가 아니라 display_name 을 쓴다.
 */
export function generateAptSlugStrict(name: string): string {
  const loose = generateAptSlug(name);
  if (!loose) return '';
  return loose.replace(/-{2,}/g, '-').replace(/^-+|-+$/g, '');
}

/**
 * 중복 판정용 키. **조회·저장에 쓰는 값이 아니다.**
 *
 * 두 파이프라인(청약 동기화 · 정비사업 승격)이 구분기호를 다르게 처리해 왔고,
 * 그 차이가 **하이픈 위치뿐**이다. 실측(특수문자 포함 활성 현장, site_type 별):
 *   subscription 467건 · trade 172건 · redevelopment 31건
 *   하이픈을 무시하면 각각 223 · 172 · 29 가 이름과 일치한다 —
 *   즉 남은 차이는 사실상 하이픈 하나다.
 *
 * 그래서 새 현장을 만들기 전에 이 키로 먼저 찾는다. 이게 없으면
 *   남천2-3-삼익비치-재건축  ←→  남천2-3삼익비치-재건축
 * 처럼 같은 현장이 두 행으로 앉는다(2026-08-25 정리한 14쌍이 전부 이 형태).
 *
 * ── ⚠️ DB 인덱스와 **정확히 같은 규칙이어야 한다** ──
 *    DB 담당이 만든 표현식 인덱스:
 *      regexp_replace(lower(slug), '[^가-힣a-z0-9]', '', 'g')
 *    한때 이 함수는 **하이픈만** 지웠는데, 병합에 쓴 키는 특수문자 전체 제거였다.
 *    둘이 어긋나면 인덱스를 못 타거나(전수 스캔) 판정이 갈린다.
 *    한쪽을 고치면 반드시 다른 쪽도 고칠 것.
 *
 * ⚠️ `generateAptSlug` 를 거치지 않는다. 그 함수는 공백을 하이픈으로 바꾸는데
 *    어차피 다 지울 것이라 한 단계가 낭비고, 규칙이 두 겹이 되면 대조가 어렵다.
 *    이름·slug 어느 쪽을 넣어도 같은 키가 나와야 한다.
 */
export function slugDupKey(slugOrName: string): string {
  return (slugOrName ?? '').toLowerCase().replace(/[^가-힣a-z0-9]/g, '');
}

/** 느슨한 규칙이 만들어 낸 값이 깨진 형태인가. 로그·점검용. */
export function isDegradedSlug(slug: string): boolean {
  return /^-|--|-$/.test(slug);
}

// slug인지 숫자 ID인지 판별
export function isNumericId(id: string): boolean {
  return /^\d+$/.test(id);
}

// s218 Track A: UUID 형식 판별 (apt_sites.id 직접 lookup 분기용)
// Supabase apt_sites 의 id 가 uuid 형. /apt/<uuid> 직접 진입 시 slug 로 잘못 lookup → 404 발생.
export function isUuid(id: string): boolean {
  return /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(id);
}
