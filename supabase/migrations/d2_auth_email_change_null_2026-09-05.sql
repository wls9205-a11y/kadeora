-- ══════════════════════════════════════════════════════════════════════════
-- ⛔⛔ 이 파일은 «준비물» 이다. 실행하지 않았고, Node 의 `!` 없이 실행하지 않는다.
--     이유: auth 스키마는 Supabase(GoTrue)가 소유한다. 우리 마이그레이션이
--     남의 스키마를 고치는 것이므로, 다음 GoTrue 업그레이드가 이 값을 다시
--     뒤집을 수 있고 그때 원인을 되짚을 근거가 필요하다. 그 근거가 이 파일이다.
-- ══════════════════════════════════════════════════════════════════════════
--
-- ── 증상 (2026-09-04 실측) ──────────────────────────────────────────────────
-- GoTrue Admin API `/admin/users` 가 500 을 낸다. 원인은 Go 드라이버가
-- `auth.users.email_change` 를 non-nullable string 으로 스캔하는데 DB 에는
-- NULL 이 들어 있는 행이 있어서다(converting NULL to string is unsupported).
-- 계정 조회가 통째로 막히므로 「가입은 됐는데 사용자 목록이 안 열린다」로 보인다.
--
-- ⚠️ 이것은 «가입 실패» 가 아니다. 9/4 07:21 kauth 504 와 섞어 읽지 않는다 —
--    그쪽은 토큰 교환 타임아웃이고(SU A-3), 이쪽은 조회 API 다.
--
-- ── 실행 전 확인 (읽기 전용 · 지금 돌려도 안전) ────────────────────────────
--   select count(*) as null_email_change from auth.users where email_change is null;
--   -- 0 이면 이미 해소됐거나 다른 원인이다. ⛔ 0 인데 실행하지 않는다.
--   ✅ 2026-09-05 실측: **400 행**. 진단이 맞다(원인 확정). 그래도 적용은 게이트 뒤다.
--
-- ── 워크어라운드 본체 (Node `!` 뒤에만) ─────────────────────────────────────
-- ⚠️ NULL → '' 다. 빈 문자열은 GoTrue 가 「변경 요청 없음」으로 읽는 값이고,
--    실제 이메일 변경 대기 중인 행에는 값이 «있으므로» 그 행은 건드리지 않는다.
--
-- update auth.users set email_change = '' where email_change is null;
--
-- ── 실행 후 재확인 ──────────────────────────────────────────────────────────
--   select count(*) from auth.users where email_change is null;   -- 기대 0
--   그리고 «API 를 실제로 불러» 200 인지 본다. 「쿼리가 0 이었다」는 확인이 아니다.
--
-- ⚠️ 같은 계열 컬럼이 더 있을 수 있다(phone_change · email_change_token_new 등).
--    500 이 남으면 그 컬럼들을 같은 방법으로 «하나씩» 확인한다 — 한꺼번에 밀지 않는다.
